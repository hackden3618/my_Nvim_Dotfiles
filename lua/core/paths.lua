M.state  = fn.stdpath("state")

--------------------------------------------------------------------------------
-- Frequently Used Paths
--------------------------------------------------------------------------------

M.lazy = M.data .. "/lazy"

M.undo = M.state .. "/undo"

M.backup = M.state .. "/backup"

M.swap = M.state .. "/swap"

return M
